package org.AnkitaK65.Unit1;

// Example6: Java Keywords

class Example6 {
    public static void main(String[] args) {

        // Total keyword count (exam-oriented)
        System.out.println("Total Java Keywords: 50\n");

        // ---------- TYPES OF KEYWORDS ----------
        System.out.println("Types of Java Keywords:");
        System.out.println("1. Data Type Keywords");
        System.out.println("2. Control Statement Keywords");
        System.out.println("3. Looping Keywords");
        System.out.println("4. Access Modifiers");
        System.out.println("5. Non-Access Modifiers");
        System.out.println("6. Object-Oriented Keywords");
        System.out.println("7. Exception Handling Keywords");
        System.out.println("8. Miscellaneous Keywords\n");

        // ---------- KEYWORDS WITH USE ----------
        System.out.println("Java Keywords with Their Use:\n");

        System.out.println("byte       : 1-byte integer data type");
        System.out.println("short      : 2-byte integer data type");
        System.out.println("int        : Integer data type");
        System.out.println("long       : Long integer data type");
        System.out.println("float      : Decimal number (single precision)");
        System.out.println("double     : Decimal number (double precision)");
        System.out.println("char       : Single Unicode character");
        System.out.println("boolean    : true or false value");
        System.out.println("void       : No return value\n");

        System.out.println("if         : Executes code when condition is true");
        System.out.println("else       : Executes code when condition is false");
        System.out.println("switch     : Multi-way decision");
        System.out.println("case       : Option in switch");
        System.out.println("default    : Executes if no case matches\n");

        System.out.println("for        : Loop with counter");
        System.out.println("while      : Loop based on condition");
        System.out.println("do         : Loop executes at least once");
        System.out.println("break      : Exit loop or switch");
        System.out.println("continue   : Skip current iteration\n");

        System.out.println("public     : Accessible everywhere");
        System.out.println("private    : Accessible only within class");
        System.out.println("protected  : Accessible within package/subclass\n");

        System.out.println("static     : Class-level member");
        System.out.println("final      : Cannot be modified");
        System.out.println("abstract   : Incomplete class or method");
        System.out.println("synchronized: Thread safety");
        System.out.println("volatile   : Variable value always from main memory");
        System.out.println("transient  : Not saved during serialization\n");

        System.out.println("class      : Defines a class");
        System.out.println("interface  : Defines interface");
        System.out.println("extends    : Inherits a class");
        System.out.println("implements : Implements interface");
        System.out.println("new        : Creates object");
        System.out.println("this       : Refers to current object");
        System.out.println("super      : Refers to parent class");
        System.out.println("instanceof : Checks object type\n");

        System.out.println("try        : Wraps risky code");
        System.out.println("catch      : Handles exception");
        System.out.println("finally   : Always executes");
        System.out.println("throw      : Throws exception explicitly");
        System.out.println("throws     : Declares exception\n");

        System.out.println("return     : Returns value from method");
        System.out.println("package    : Groups classes");
        System.out.println("import     : Access classes from package");
        System.out.println("enum       : Fixed set of constants");
        System.out.println("assert     : Debugging check\n");

        // ---------- RESERVED BUT NOT USED ----------
        System.out.println("Reserved but not used keywords:");
        System.out.println("goto, const\n");

        // ---------- NOTES ----------
        System.out.println("Important Notes on Java Keywords:");
        System.out.println("- Keywords are reserved words");
        System.out.println("- Keywords cannot be used as identifiers");
        System.out.println("- Java keywords are case-sensitive");
        System.out.println("- true, false, null are literals (not keywords)");
        System.out.println("- final, finally, finalize have different meanings");
    }
}

